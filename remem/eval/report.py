def _bar_by_family(ax, main, systems, families, metric, scale=1.0):
    n = len(systems)
    w = 0.8 / n
    for i, s in enumerate(systems):
        xs, ys, es = [], [], []
        for j, f in enumerate(families):
            node = main.get(s, {}).get(f, {}).get(metric)
            if node is None:
                continue
            xs.append(j + (i - (n - 1) / 2) * w)
            ys.append(scale * node["mean"])
            es.append(0 if math.isnan(node["ci95"]) else scale * node["ci95"])
        ax.bar(xs, ys, w, yerr=es, label=NAMES[s], color=COLORS.get(s), capsize=2, error_kw={"lw": 0.8})
    ax.set_xticks(range(len(families)))
    ax.set_xticklabels(families, rotation=30, ha="right", fontsize=8)


def _plots(plots: Path, agg: dict, curves: dict, growth: dict, calib: dict, families: list[str]) -> None:
    main = agg["main"].get("first", {})
    if not main:
        return
    core = ["A_vector", "B_static", "C_remem"]
    fams = families + ["HEADLINE"]
    for metric, title, scale, fname, ylab in [
        ("task_success", "Task success", 100, "task_success.png", "%"),
        ("gold_recall", "Retrieval recall (gold memories in context)", 100, "retrieval_recall.png", "%"),
        ("context_precision", "Memory precision (share of context that is gold)", 100, "memory_precision.png", "%"),
        ("tokens_per_task", "Tokens consumed per task", 1, "token_usage.png", "tokens"),
        ("latency_ms_mean", "Retrieval latency per task", 1, "latency.png", "ms"),
    ]:
        fig, ax = plt.subplots(figsize=(10, 4))
        _bar_by_family(ax, main, core, fams, metric, scale)
        ax.set_title(title + " (mean ± 95% CI over seeds, reader: first)")
        ax.set_ylabel(ylab)
        ax.legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(plots / fname, dpi=130)
        plt.close(fig)

    # ablation
    abl = ["abl0_base", "abl1_temporal", "abl2_utility_heuristic", "abl3_learned_model", "abl4_outcome_feedback",
           "abl5_retention", "abl6_contradiction", "abl7_cost_aware"]
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    for ax, metric, scale, ylab in ((axes[0], "task_success", 100, "task success %"), (axes[1], "tokens_per_task", 1, "tokens/task")):
        ys = [scale * main[s]["HEADLINE"][metric]["mean"] for s in abl if s in main]
        es = [scale * (main[s]["HEADLINE"][metric]["ci95"] if not math.isnan(main[s]["HEADLINE"][metric]["ci95"]) else 0)
              for s in abl if s in main]
        ax.bar(range(len(ys)), ys, yerr=es, color="#54a24b", capsize=2)
        ax.set_xticks(range(len(ys)))
        ax.set_xticklabels([NAMES[s].replace("+ ", "+") for s in abl if s in main], rotation=40, ha="right", fontsize=7)
        ax.set_ylabel(ylab)
    fig.suptitle("Cumulative ablation (headline families, reader: first)")
    fig.tight_layout()
    fig.savefig(plots / "ablation.png", dpi=130)
    plt.close(fig)

    # learning curves
    cf = [f for f in ("distractor", "useless_frequent", "contradiction", "state_change") if f in curves]
    if cf:
        fig, axes = plt.subplots(1, len(cf), figsize=(4 * len(cf), 3.4), squeeze=False)
        for ax, f in zip(axes[0], cf):
            for s in core:
                if s in curves[f]:
                    ax.plot(range(1, CURVE_BINS + 1), [100 * v for v in curves[f][s]["success_seq"]], marker="o", ms=3,
                            label=NAMES[s], color=COLORS[s])
            ax.set_title(f, fontsize=9)
            ax.set_xlabel("stream decile")
            ax.set_ylabel("task success %")
        axes[0][0].legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(plots / "learning_curves.png", dpi=130)
        plt.close(fig)
    # exposure of traps / hubs over time (frequently-retrieved-but-useless)
    if "useless_frequent" in curves:
        fig, ax = plt.subplots(figsize=(5.5, 3.4))
        for s in core:
            if s in curves["useless_frequent"]:
                ax.plot(range(1, CURVE_BINS + 1), curves["useless_frequent"][s]["trap_seq"], marker="o", ms=3,
                        label=NAMES[s], color=COLORS[s])
        ax.set_title("useless_frequent: trap/hub memories served per task", fontsize=9)
        ax.set_xlabel("stream decile")
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(plots / "useless_exposure.png", dpi=130)
        plt.close(fig)

    # memory growth
    gf = [f for f in ("distractor", "rare_critical", "long_horizon") if f in growth and "C_remem" in growth[f]]
    if gf:
        fig, axes = plt.subplots(1, len(gf), figsize=(4.4 * len(gf), 3.4), squeeze=False)
        for ax, f in zip(axes[0], gf):
            for s, ls in (("C_remem", "-"), ("ret_frequency_prune", "--"), ("A_vector", ":")):
                if s in growth[f]:
                    snaps = growth[f][s]
                    ax.plot([x["n_tasks"] for x in snaps], [x["served_tokens"] for x in snaps], ls, label=f"{NAMES[s]} served tokens",
                            color=COLORS.get(s))
            snaps = growth[f]["C_remem"]
            ax.plot([x["n_tasks"] for x in snaps], [x["total_tokens"] for x in snaps], "-", color="#bbbbbb", label="all stored tokens")
            ax.set_title(f, fontsize=9)
            ax.set_xlabel("tasks processed")
            ax.set_ylabel("memory tokens eligible for retrieval")
        axes[0][0].legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(plots / "memory_growth.png", dpi=130)
        plt.close(fig)
        fig, axes = plt.subplots(1, len(gf), figsize=(4.4 * len(gf), 3.4), squeeze=False)
        for ax, f in zip(axes[0], gf):
            snaps = growth[f]["C_remem"]
            xs = [x["n_tasks"] for x in snaps]
            bottom = [0] * len(xs)
            for st, c in (("ACTIVE", "#54a24b"), ("LOW_VALUE", "#eeca3b"), ("COMPRESSED", "#f58518"),
                          ("ARCHIVED", "#e45756"), ("INVALIDATED", "#79706e")):
                vals = [x["states"][st] for x in snaps]
                ax.bar(xs, vals, 20, bottom=bottom, color=c, label=st)
                bottom = [b + v for b, v in zip(bottom, vals)]
            ax.set_title(f"{f}: memory states (D)", fontsize=9)
            ax.set_xlabel("tasks processed")
        axes[0][0].legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(plots / "memory_states.png", dpi=130)
        plt.close(fig)

    # utility prediction quality
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    ax = axes[0]
    for s in ("A_vector", "C_remem"):
        node = main.get(s, {}).get("HEADLINE", {})
        if "utility_auc" in node:
            ax.bar(NAMES[s], node["utility_auc"]["mean"], yerr=0 if math.isnan(node["utility_auc"]["ci95"]) else node["utility_auc"]["ci95"],
                   color=COLORS[s], capsize=2)
    ax.set_ylim(0.5, 1.0)
    ax.set_ylabel("AUC for 'candidate is gold'")
    ax.set_title("Score quality over considered candidates", fontsize=9)
    ax.tick_params(axis="x", labelsize=7)
    ax = axes[1]
    if "C_remem" in calib:
        pts = calib["C_remem"]
        ax.plot([p[0] for p in pts], [p[1] for p in pts], "o-", color=COLORS["C_remem"], label="ReMem")
        ax.plot([0, 1], [0, 1], "--", color="#999999")
        ax.set_xlabel("predicted P(contributes)")
        ax.set_ylabel("observed gold rate")
        ax.set_title("Reliability of the learned utility", fontsize=9)
    fig.tight_layout()
    fig.savefig(plots / "utility_quality.png", dpi=130)
    plt.close(fig)

    # budget curve
    bud = [f for f in ("budget_tight", "budget_medium", "distractor") if f in main.get("C_remem", {})]
    if len(bud) >= 2:
        label = {"budget_tight": "45 tok", "budget_medium": "75 tok", "distractor": "no budget"}
        fig, ax = plt.subplots(figsize=(5.5, 3.6))
        for s in core:
            ys = [100 * main[s][f]["task_success"]["mean"] for f in bud]
            ax.plot([label[f] for f in bud], ys, marker="o", label=NAMES[s], color=COLORS[s])
        ax.set_ylabel("task success %")
        ax.set_title("Success vs context budget", fontsize=9)
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(plots / "budget_curve.png", dpi=130)
        plt.close(fig)


CURVE_BINS = 10
