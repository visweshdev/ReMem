def _f(d: dict | None, k: str, pct: bool = False, digits: int = 3) -> str:
    if not d or k not in d or d[k]["mean"] is None or (isinstance(d[k]["mean"], float) and math.isnan(d[k]["mean"])):
        return "–"
    m, ci = d[k]["mean"], d[k]["ci95"]
    if pct:
        m, ci = 100 * m, 100 * ci
        return f"{m:.1f}" + ("" if math.isnan(ci) else f" ±{ci:.1f}")
    return f"{m:.{digits}f}" + ("" if math.isnan(ci) else f" ±{ci:.{digits}f}")


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _sys_rows(main: dict, systems: list[str], fam: str, cols: list[tuple[str, str, bool]]) -> list[list[str]]:
    rows = []
    for s in systems:
        node = main.get(s, {}).get(fam)
        if node is None:
            continue
        rows.append([NAMES.get(s, s)] + [_f(node, k, pct) for _, k, pct in cols])
    return rows


def write_all(out: Path, agg: dict, curves: dict, growth: dict, calib: dict, fa: dict, paired: dict,
              families: list[str]) -> None:
    plots = out / "plots"
    plots.mkdir(parents=True, exist_ok=True)
    md = ["# Results (auto-generated by experiments/run_benchmark.py)\n",
          "All numbers are means over test seeds with 95% t-intervals (±). Success etc. in %. "
          "See README for what the simulated agent and the stub encoders do and do not show.\n"]
    main_all = agg["main"]
    core_cols = [("Task success %", "task_success", True), ("Gold recall %", "gold_recall", True),
                 ("Context precision %", "context_precision", True), ("Tokens/task", "tokens_per_task", False),
                 ("Latency ms", "latency_ms_mean", False)]
    for mode in ("first", "latest"):
        main = main_all.get(mode, {})
        if not main:
            continue
        md.append(f"\n## Main comparison, reader mode `{mode}` (mean over headline families)\n")
        md.append(_table(["System"] + [c[0] for c in core_cols],
                         _sys_rows(main, ["A_vector", "B_static", "rmm_style", "C_remem"],
                                   "HEADLINE", core_cols)))
        md.append(f"\n### Task success % per family, reader mode `{mode}`\n")
        rows = []
        for s in ["A_vector", "B_static", "C_remem"]:
            rows.append([NAMES[s]] + [_f(main.get(s, {}).get(f), "task_success", True) for f in families])
        md.append(_table(["System"] + families, rows))

    main = main_all.get("first", {})
    if main:
        md.append("\n## Cumulative ablation (reader `first`, headline families)\n")
        abl = ["abl0_base", "abl1_temporal", "abl2_utility_heuristic", "abl3_learned_model", "abl4_outcome_feedback",
               "abl5_retention", "abl6_contradiction", "abl7_cost_aware"]
        cols = core_cols[:1] + [("Task success, 2nd half %", "task_success_second_half", True)] + core_cols[1:]
        md.append(_table(["System"] + [c[0] for c in cols], _sys_rows(main, abl, "HEADLINE", cols)))
        md.append("\nPer-family task success % for the same rows:\n")
        hf = [f for f in families if f in {"distractor", "long_horizon", "contradiction", "rare_critical",
                                           "useless_frequent", "budget_tight", "state_change"}]
        md.append(_table(["System"] + hf, [[NAMES[s]] + [_f(main.get(s, {}).get(f), "task_success", True) for f in hf]
                                          for s in abl if s in main]))
        md.append("\n## Leave-one-out from the full system (reader `first`)\n")
        loo = ["C_remem", "loo_no_feedback", "loo_no_contradiction", "loo_no_retention", "loo_no_cost_aware",
               "loo_heuristic_utility", "loo_no_exclusive_schema"]
        md.append(_table(["System"] + [c[0] for c in cols], _sys_rows(main, loo, "HEADLINE", cols)))
        md.append("\n## Credit-assignment methods (same system, reader `first`)\n")
        att_cols = [("Task success %", "task_success", True), ("Credit precision", "attr_precision", False),
                    ("Credit recall", "attr_recall", False), ("Extra agent calls/task", "extra_agent_calls_per_task", False)]
        md.append(_table(["Attribution"] + [c[0] for c in att_cols],
                         _sys_rows(main, ["attr_presence", "attr_usage_only", "C_remem", "attr_signals_loo"], "HEADLINE", att_cols)))
        md.append("\nCredit precision/recall are measured against hidden gold on successful tasks.\n")
        md.append("\n## Utility prediction quality (reader `first`, candidates the system considered)\n")
        uq = [("AUC of system score", "utility_auc", False), ("AUC of similarity alone", "sim_auc", False),
              ("Brier", "utility_brier", False), ("ECE", "utility_ece", False)]
        md.append(_table(["System"] + [c[0] for c in uq],
                         _sys_rows(main, ["A_vector", "C_remem", "loo_heuristic_utility"], "HEADLINE", uq)))
        md.append("\nBrier/ECE are only meaningful for systems whose score is a probability (the learned model).\n")
        md.append("\n## Rare-but-critical and retention (family `rare_critical`, reader `first`)\n")
        rc = [("Task success %", "task_success", True), ("Success on dormant-critical %", "success_critical_dormant", True),
              ("Success on shown-critical %", "success_critical_shown", True),
              ("ARCHIVED", "state_ARCHIVED", False), ("COMPRESSED", "state_COMPRESSED", False)]
        md.append(_table(["System"] + [c[0] for c in rc],
                         _sys_rows(main, ["A_vector", "C_remem", "loo_no_retention", "ret_frequency_prune"], "rare_critical", rc)))
        md.append("\n## Contradiction handling audit (family `contradiction` and `state_change`)\n")
        ca = [("Task success %", "task_success", True), ("Success on historical %", "success_historical", True),
              ("Stale-in-context task rate %", "stale_task_rate", True),
              ("False invalidations", "false_invalidations", False), ("Missed invalidations", "missed_invalidations", False)]
        for fam in ("contradiction", "state_change"):
            md.append(f"\n`{fam}`:\n")
            md.append(_table(["System"] + [c[0] for c in ca],
                             _sys_rows(main, ["A_vector", "B_static", "C_remem", "loo_no_contradiction",
                                              "loo_no_exclusive_schema"], fam, ca)))
        md.append("\n## Memory growth at end of stream (reader `first`, headline families)\n")
        mg = [("Memories", "mem_total", False), ("ACTIVE", "state_ACTIVE", False), ("LOW_VALUE", "state_LOW_VALUE", False),
              ("COMPRESSED", "state_COMPRESSED", False), ("ARCHIVED", "state_ARCHIVED", False),
              ("INVALIDATED", "state_INVALIDATED", False), ("Served tokens / total", "mem_served_tokens", False)]
        md.append(_table(["System"] + [c[0] for c in mg],
                         _sys_rows(main, ["A_vector", "C_remem", "ret_frequency_prune"], "HEADLINE", mg)))

    if paired:
        md.append("\n## Paired differences over seeds (headline families)\n")
        rows = []
        for k, v in paired.items():
            mode, metric, pair = k.split("|")
            if metric not in ("task_success", "tokens_per_task"):
                continue
            scale = 100 if metric == "task_success" else 1
            unit = "pp" if metric == "task_success" else "tok"
            ci = "" if math.isnan(v["ci95"]) else f" ±{scale * v['ci95']:.1f}"
            rows.append([mode, metric, pair, f"{scale * v['delta']:+.1f}{ci} {unit}"])
        md.append(_table(["Reader", "Metric", "Difference", "Mean ± 95% CI"], rows))

    if main:
        md.append("\n## New in ReMem (reader `first`)\n")
        md.append("### Safeguard against demoting correct memories, and exploration (core families)\n")
        gc = [("Task success %", "task_success", True), ("Gold recall %", "gold_recall", True),
              ("Tasks where utility pushed out a top-5-similar gold %", "utility_demoted_gold_rate", True),
              ("Context precision %", "context_precision", True), ("Tokens/task", "tokens_per_task", False)]
        md.append(_table(["System"] + [c[0] for c in gc],
                         _sys_rows(main, ["A_vector", "loo_no_guard", "C_remem", "new_thompson"], "HEADLINE", gc)))
        md.append("\n### Learned single-valued-attribute schema (none given vs given vs learned)\n")
        sc = [("Task success %", "task_success", True), ("Stale-in-context task rate %", "stale_task_rate", True),
              ("Missed invalidations", "missed_invalidations", False), ("False invalidations", "false_invalidations", False)]
        nocue = agg.get("no_update_cue", {}).get("first", {})
        for label, src in (("explicit update wording present (default worlds)", main), ("no explicit update wording (cue path useless)", nocue)):
            if not src:
                continue
            for fam in ("contradiction", "state_change"):
                md.append(f"\n`{fam}`, {label}:\n")
                md.append(_table(["System"] + [c[0] for c in sc],
                                 _sys_rows(src, ["A_vector", "C_remem", "loo_no_exclusive_schema", "schema_learned"], fam, sc)))
        md.append("\n### Cheaper leave-one-out credit assignment\n")
        lc = [("Task success %", "task_success", True), ("Credit precision", "attr_precision", False),
              ("Credit recall", "attr_recall", False), ("Extra agent calls/task", "extra_agent_calls_per_task", False)]
        md.append(_table(["Attribution"] + [c[0] for c in lc],
                         _sys_rows(main, ["C_remem", "attr_signals_loo_ambiguous", "attr_signals_loo"], "HEADLINE", lc)))

    sens = {t: v for t, v in agg.items() if t not in ("main", "no_update_cue")}
    if sens:
        md.append("\n## Sensitivity (reader `first`, headline families unless noted; task success %)\n")
        rows = []
        for tag in sorted(sens):
            node = sens[tag].get("first", {})
            for s in ["A_vector", "B_static", "C_remem"]:
                if s in node:
                    rows.append([tag, NAMES[s], _f(node[s].get("HEADLINE"), "task_success", True)])
        md.append(_table(["Perturbation", "System", "Task success %"], rows))
        md.append("\n`feedback_noise_x`: the environment flips the success signal with probability x. "
                  "`distraction_x`: per-irrelevant-item distraction probability of the agent (default 0.05). "
                  "`extraction_noise_0.2`: the extractor misses the attribute key for 20% of facts "
                  "(families contradiction and state_change only).\n")

    (out / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    _write_failures(out, fa)
    _plots(plots, agg, curves, growth, calib, families)


def _write_failures(out: Path, fa: dict) -> None:
    md = ["# Failure analysis (auto-generated)\n",
          "Counts are per-task tags over all test seeds, reader mode `first`; a task may carry several tags. "
          "Rates are per task. Examples are the first ones encountered, not cherry-picked successes.\n"]
    systems = [s for s in ("A_vector", "B_static", "C_remem") if s in fa["counts"]]
    tot = {s: sum(fa["n_tasks"][s].values()) for s in systems}
    rows = []
    for cat in CATEGORIES:
        r = [f"`{cat}`"]
        for s in systems:
            c = sum(d.get(cat, 0) for d in fa["counts"][s].values())
            r.append(f"{c} ({100 * c / tot[s]:.1f}%)")
        rows.append(r)
    md.append(_table(["Category"] + [NAMES[s] for s in systems], rows))
    md.append("\n## Per family (D ReMem)\n")
    if "C_remem" in fa["counts"]:
        fams = sorted(fa["counts"]["C_remem"])
        rows = []
        for cat in CATEGORIES:
            rows.append([f"`{cat}`"] + [str(fa["counts"]["C_remem"][f].get(cat, 0)) for f in fams])
        md.append(_table(["Category"] + fams, rows))
    for s in ("C_remem", "A_vector"):
        if s not in fa["examples"]:
            continue
        md.append(f"\n## Examples: {NAMES[s]}\n")
        for cat in CATEGORIES:
            exs = fa["examples"][s].get(cat, [])
            if not exs:
                continue
            md.append(f"\n### `{cat}`\n")
            for ex in exs[:3]:
                md.append(f"- **{ex['family']} seed {ex['seed']} task {ex['task_id']}** ({ex['kind']}, "
                          f"success={ex['success']}): _{ex['query']}_")
                for g in ex["gold"]:
                    md.append(f"  - gold `{g['id']}` pool_rank={g['pool_rank']} ctx_pos={g['ctx_pos']} state={g['state']}: {g['text']}")
                for sl in ex["selected"]:
                    md.append(f"  - served [{sl['kind']}/{sl['state']}] {sl['text']}")
                md.append(f"  - agent distracted={ex['agent_distracted']} guessed={ex['agent_guessed']}")
    (out / "failure_analysis.md").write_text("\n".join(md) + "\n", encoding="utf-8")


